// Generates the dotted world map used in the "Made in Lagos" section.
//
// Run with: npm run generate:map
// Output:   src/data/world-map.ts (committed, so this only needs to run
//           again if you change the highlighted countries or the grid).
//
// The map is drawn as two SVG paths of zero-length round-capped strokes,
// which keeps thousands of dots down to a few kilobytes of markup.

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoContains, geoNaturalEarth1 } from "d3-geo";

const require = createRequire(import.meta.url);
const topology = require("world-atlas/countries-110m.json");

const here = dirname(fileURLToPath(import.meta.url));
const outFile = process.argv[2] ?? resolve(here, "../src/data/world-map.ts");

const WIDTH = 1000;
const SPACING = 8; // distance between dots, in viewBox units

// ISO 3166-1 numeric codes, as used by world-atlas.
// `marker` is where the location pin sits (lon, lat).
const HIGHLIGHTS = [
  { id: "458", name: "Malaysia", marker: [101.69, 3.14] },
  { id: "566", name: "Nigeria", marker: [3.38, 6.52] },
  { id: "360", name: "Indonesia", marker: [110.4, -7.2] },
  // The Aleutians cross the antimeridian, which makes a naive point-in-polygon
  // test light up eastern Russia, so limit the US to the western hemisphere.
  { id: "840", name: "United States", marker: [-98.5, 39.5], lonRange: [-180, -60] },
  { id: "834", name: "Tanzania", marker: [34.9, -6.4] },
  { id: "144", name: "Sri Lanka", marker: [80.7, 7.8] },
  { id: "800", name: "Uganda", marker: [32.4, 1.4] },
];

const land = feature(topology, topology.objects.land);
const countries = feature(topology, topology.objects.countries).features;
const highlighted = HIGHLIGHTS.map((h) => {
  const f = countries.find((c) => String(c.id).padStart(3, "0") === h.id);
  if (!f) throw new Error(`Country ${h.name} (${h.id}) not found in world-atlas`);
  return { ...h, feature: f };
});

// Fit the projection to everything north of Antarctica.
const projection = geoNaturalEarth1();
projection.fitWidth(WIDTH, {
  type: "Feature",
  geometry: {
    type: "Polygon",
    coordinates: [[[-180, -58], [180, -58], [180, 84], [-180, 84], [-180, -58]]],
  },
});
const [[, top], [, bottom]] = [projection([0, 84]), projection([0, -58])];
const height = Math.ceil(bottom - top);
projection.translate([projection.translate()[0], projection.translate()[1] - top]);

const base = [];
const accent = [];
// Natural Earth is pseudo-cylindrical: y depends only on latitude, and x is
// linear in longitude along each row. Solving each row directly avoids the
// iterative inverse, which returns wrapped longitudes near the map edges.
const cx = projection([0, 0])[0];
for (let y = SPACING / 2; y < height; y += SPACING) {
  const lat = projection.invert([cx, y])[1];
  if (lat < -58) continue;
  const unit = projection([1, lat])[0] - cx; // x distance per degree of longitude
  for (let x = SPACING / 2; x < WIDTH; x += SPACING) {
    const lon = (x - cx) / unit;
    if (Math.abs(lon) > 180) continue;
    const lonLat = [lon, lat];
    if (!geoContains(land, lonLat)) continue;
    const hit = highlighted.some(
      (h) => (!h.lonRange || (lonLat[0] >= h.lonRange[0] && lonLat[0] <= h.lonRange[1])) && geoContains(h.feature, lonLat),
    );
    (hit ? accent : base).push([x, y]);
  }
}

// Encode dots as "M x y h0" with relative moves inside a row to keep it short.
function encode(points) {
  let d = "";
  let prev = null;
  for (const [x, y] of points) {
    if (prev && prev[1] === y) d += `m${round(x - prev[0])} 0h0`;
    else d += `M${round(x)} ${round(y)}h0`;
    prev = [x, y];
  }
  return d;
}
const round = (n) => Math.round(n * 10) / 10;

const markers = highlighted.map((h) => {
  const [x, y] = projection(h.marker);
  return { id: h.id, name: h.name, x: round(x), y: round(y) };
});

const file = `// Generated by scripts/generate-world-map.mjs. Do not edit by hand.
// Source: Natural Earth via world-atlas (public domain).

export const worldMap = {
  width: ${WIDTH},
  height: ${height},
  dotSize: ${round(SPACING * 0.55)},
  base: ${JSON.stringify(encode(base))},
  accent: ${JSON.stringify(encode(accent))},
  markers: ${JSON.stringify(markers, null, 2)},
} as const;
`;

writeFileSync(outFile, file);
console.log(`Wrote ${outFile}: ${base.length + accent.length} dots (${accent.length} highlighted), ${(file.length / 1024).toFixed(1)} KB`);
